export type QmahIconName = keyof typeof ICONS;

@Component({
  selector: 'app-qmah-icon',
  standalone: true,
  imports: [NgComponentOutlet],
  template: '<ng-container *ngComponentOutlet="iconComponent(); inputs: iconInputs()"></ng-container>',
  styleUrl: './qmah-icon.scss',
})
export class QmahIconComponent {
  readonly name = input.required<QmahIconName>();
  readonly size = input<number | string>(18);
  readonly strokeWidth = input<number | string>(1.8);

  protected readonly iconComponent = computed<Type<unknown>>(() => ICONS[this.name()]);
  protected readonly iconInputs = computed(() => ({
    size: this.size(),
    strokeWidth: this.strokeWidth(),
  }));
}
